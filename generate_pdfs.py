def parse_and_add_markdown(pdf, markdown_text):
    """Parse markdown and add to PDF"""
    lines = markdown_text.split('\n')
    i = 0

    while i < len(lines):
        line = lines[i]

        # Handle headings
        if line.startswith('# '):
            title = safe_text(line[2:].strip())
            pdf.add_section_heading(title, level=1)
            i += 1
        elif line.startswith('## '):
            title = safe_text(line[3:].strip())
            pdf.add_section_heading(title, level=2)
            i += 1
        elif line.startswith('### '):
            title = safe_text(line[4:].strip())
            pdf.add_section_heading(title, level=3)
            i += 1
        elif line.startswith('|') and line.endswith('|') and not line.startswith('|---'):
            # Table
            table_headers = []
            table_rows = []
            data_start = i

            # Collect all rows before separator
            r = i
            all_rows_before_sep = []
            while r < len(lines) and not (lines[r].strip().startswith('|---') or lines[r].strip().startswith('|--')):
                if lines[r].strip().startswith('|') and lines[r].strip() != '|':
                    row_data = [c.strip() for c in lines[r].strip().split('|')[1:-1]]
                    all_rows_before_sep.append(row_data)
                r += 1

            if all_rows_before_sep:
                table_headers = [safe_text(h) for h in all_rows_before_sep[0]]
                table_rows = all_rows_before_sep[1:]
                # Clean up empty rows
                table_rows = [row for row in table_rows if any(cell != '' for cell in row)]

            # Determine column widths
            n_cols = max(len(table_headers), max(len(row) for row in table_rows) if table_rows else 1)
            if n_cols > 0:
                base_width = 180 / n_cols
                col_widths = [base_width] * n_cols
            else:
                col_widths = [180]

            if table_rows:
                pdf.add_table(table_headers, table_rows, col_widths)

            i = r + 1 if r < len(lines) else i + 1
            continue

        # Handle bold text (double asterisk)
        elif line.startswith('**') and line.endswith('**'):
            text = safe_text(line.strip('*').strip())
            pdf.add_bold_text(text)
            i += 1

        # Handle list items
        elif line.startswith('- ') or line.startswith('* '):
            text = safe_text(line[2:].strip())
            pdf.set_font('DejaVu', '', 9.5)
            pdf.cell(5, 5, '')
            pdf.multi_cell(0, 5, f'* {text}', new_x="LMARGIN", new_y="NEXT")
            i += 1

        # Skip double blank lines
        elif line.strip() == '' and i > 0 and lines[i - 1].strip() == '':
            i += 1
            continue

        # Handle git/command output lines
        elif line.strip().startswith('Git ') or line.strip().startswith('commit ') or line.strip().startswith('$ '):
            pdf.set_font('DejaVu', '', 7.5)
            # Safe the line text
            pdf.multi_cell(0, 4.2, safe_text(line), new_x="LMARGIN", new_y="NEXT")
            pdf.set_font('DejaVu', '', 9.5)
            i += 1

        # Handle code blocks
        elif line.strip().startswith('```') or (len(line) >= 4 and line[:4] == '    '):
            code_lines = []
            if i < len(lines) and (lines[i].strip().startswith('```') or lines[i].startswith('    ')):
                j = i + 1
                while j < len(lines) and not (lines[j].strip().startswith('```') or (len(lines[j]) >= 4 and lines[j][:4] == '    ')):
                    code_lines.append(lines[j])
                    j += 1
                code_text = '\n'.join(code_lines)
                pdf.set_font('DejaVu', '', 7)
                pdf.multi_cell(0, 3.8, safe_text(code_text), new_x="LMARGIN", new_y="NEXT")
                pdf.set_font('DejaVu', '', 9.5)
                i = j + 1 if j < len(lines) else i + 1
                continue
            else:
                i += 1

        # Regular body text
        else:
            if line.strip():
                pdf.set_font('DejaVu', '', 9.5)
                pdf.multi_cell(0, 5, safe_text(line), new_x="LMARGIN", new_y="NEXT")
            i += 1


def generate_pdf_report(markdown_path, pdf_output_path, report_title):
    """Generate a PDF from a markdown report file"""
    with open(markdown_path, 'r', encoding='utf-8') as f:
        content = f.read()

    pdf = AuditPDF()
    pdf.add_title_page()
    parse_and_add_markdown(pdf, content)
    pdf.output(pdf_output_path)
    return os.path.getsize(pdf_output_path)


