def safe_text(text):
    """Ensure text contains only Latin-1 encodable characters, replacing others"""
    # Replace common Unicode characters with ASCII equivalents
    replacements = {
        '\u2705': 'PASS',  # check mark
        '\u2716': 'FAIL',  # X mark
        '\u2190': '<-',    # left arrow
        '\u2191': '^',     # up arrow
        '\u2193': 'v',     # down arrow
        '\u2192': '->',    # right arrow
        '\u2022': '*',     # bullet -> asterisk
        '\u2265': '>=',    # >=
        '\u2264': '<=',    # <=
        '\u2260': '!=',    # !=
        '\u2265': '>=',    # >=
        '\u00b1': '+/-',   # plus-minus
        '\u00d7': 'x',     # multiplication
        '\u00f7': '/',     # division (÷)
    }
    result = text
    for unicode_char, ascii_repl in replacements.items():
        result = result.replace(unicode_char, ascii_repl)
    return result


def add_table(self, headers, rows, col_widths=None):
    """Add a formatted table to the PDF using DejaVu font"""
    if col_widths is None:
        available_width = 180
        n_cols = max(len(headers), max(len(row) for row in rows) if rows else 1)
        col_widths = [available_width / n_cols] * n_cols

    # Check if we need a new page
    est_height = 10 + len(rows) * 7
    if self.get_y() + est_height > 270:
        self.add_page()

    # Header row - use safe text
    safe_headers = [safe_text(h) for h in headers]
    self.set_font('DejaVu', 'B', 7)
    self.set_fill_color(41, 65, 117)
    self.set_text_color(255, 255, 255)

    y_start = self.get_y()
    x = 10

    for i, header in enumerate(safe_headers):
        self.set_xy(x, y_start)
        self.cell(col_widths[i], 6, header, border=1, fill=True, new_x="RIGHT", new_y="TOP")
        x += col_widths[i]

    y_after_header = self.get_y()

    # Data rows
    self.set_text_color(0, 0, 0)
    self.set_font('DejaVu', '', 6.5)

    for row_idx, row in enumerate(rows):
        safe_row = [safe_text(cell) for cell in row]

        # Calculate needed height
        max_lines = 1
        for i, cell_text in enumerate(safe_row):
            chars_per_line = max(1, int(col_widths[i] / 1.7))
            n_lines = max(1, (len(cell_text) + chars_per_line - 1) // chars_per_line)
            max_lines = max(max_lines, n_lines)

        row_h = max(5, max_lines * 3.5)

        # Check if we need a new page for this row
        if self.get_y() + row_h > 270:
            self.add_page()
            # Re-draw header
            self.set_font('DejaVu', 'B', 7)
            self.set_fill_color(41, 65, 117)
            self.set_text_color(255, 255, 255)
            y_start = self.get_y()
            x = 10
            for i, header in enumerate(safe_headers):
                self.set_xy(x, y_start)
                self.cell(col_widths[i], 6, header, border=1, fill=True, new_x="RIGHT", new_y="TOP")
                x += col_widths[i]
            y_after_header = self.get_y()
            self.set_text_color(0, 0, 0)
            self.set_font('DejaVu', '', 6.5)

        y_row = self.get_y()
        x = 10

        for i, cell_text in enumerate(safe_row):
            self.set_xy(x + 1, y_row + 1)
            self.multi_cell(col_widths[i] - 2, 3.2, cell_text, border=0, new_x="RIGHT", new_y="TOP")
            x += col_widths[i]

        # Move to after the row
        self.ln()

    self.ln(3)


